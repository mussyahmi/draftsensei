export const STRINGS: Record<Lang, Strings> = { en, ms, id };

export const isLang = (v: unknown): v is Lang => v === 'en' || v === 'ms' || v === 'id';

// A first visit from a phone set to Malay or Indonesian starts in that language.
export const langFor = (browser: string | undefined): Lang => {
  const code = browser?.toLowerCase() ?? '';
  if (code.startsWith('ms')) return 'ms';
  return /^(id|in)\b/.test(code) ? 'id' : 'en';
};
